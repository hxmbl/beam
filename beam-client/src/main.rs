use beam_common::{
    ClientMessage, PROTOCOL_VERSION, ProtocolError, Result, ServerMessage, compute_blake3_file,
    frame, read_handshake, version_mismatch_message,
};
use clap::{Parser, Subcommand};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::net::{SocketAddr, ToSocketAddrs};
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::Arc;
use tokio::io::{AsyncBufReadExt, AsyncWriteExt, BufReader};
use tokio::net::{TcpListener, TcpStream};
use tokio::sync::Mutex;
use uuid::Uuid;

mod prompt;
mod ssh;
use prompt::{Decision, PromptConfig};

#[derive(Parser)]
#[command(
    name = "beam-client",
    version,
    about = "Beam client - serves binaries to remote servers over SSH"
)]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Start listening for requests from a server
    Listen {
        /// Session ID (generated by shell wrapper)
        #[arg(long)]
        session_id: String,
        /// Port to listen on (0 = auto-assign)
        #[arg(long, default_value = "0")]
        port: u16,
        /// Host to bind to
        #[arg(long, default_value = "127.0.0.1")]
        host: String,
        /// SSH target host (for setting up reverse forward)
        #[arg(long)]
        ssh_host: Option<String>,
        /// Path to SSH control socket
        #[arg(long)]
        control_path: Option<String>,
    },
    /// Run ssh with Beam: start a listener, add the reverse forward and
    /// SendEnv options, and answer the server's requests (used by the shell
    /// wrapper: `beam-client ssh -- <ssh args>`)
    Ssh {
        /// Arguments for ssh, passed through unchanged
        #[arg(trailing_var_arg = true, allow_hyphen_values = true)]
        args: Vec<String>,
    },
    /// Print the shell integration script (eval it from your shell rc)
    ShellInit {
        /// Shell type (bash, zsh, fish)
        #[arg(long, default_value = "bash")]
        shell: String,
    },
    /// Find a binary on the client
    FindBinary {
        /// Command name
        command: String,
    },
    /// Compute BLAKE3 hash of a file
    Hash {
        /// File path
        path: PathBuf,
    },
}

#[derive(Debug, Clone)]
#[allow(dead_code)]
struct SessionInfo {
    session_id: String,
    port: u16,
}

struct BeamClient {
    sessions: Arc<Mutex<HashMap<String, SessionInfo>>>,
    binary_cache: Arc<Mutex<HashMap<String, BinaryMetadata>>>,
    config: ClientConfig,
}

#[derive(Debug, Clone)]
#[allow(dead_code)]
struct ClientConfig {
    cache_dir: PathBuf,
    allowed_paths: Vec<PathBuf>,
    prompt: PromptConfig,
}

/// A server's request for a binary, as received on the wire.
struct BinaryRequest {
    session_id: String,
    command: String,
    args: Vec<String>,
    arch: String,
    os: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct BinaryMetadata {
    path: PathBuf,
    size: u64,
    blake3_hash: String,
    arch: String,
    os: String,
}

impl Default for ClientConfig {
    fn default() -> Self {
        let cache_dir = dirs::cache_dir()
            .unwrap_or_else(|| PathBuf::from("."))
            .join("beam");

        Self {
            cache_dir,
            allowed_paths: vec![
                PathBuf::from("/usr/bin"),
                PathBuf::from("/usr/local/bin"),
                PathBuf::from("/bin"),
                PathBuf::from("/opt/homebrew/bin"),
                PathBuf::from("/opt/local/bin"),
            ],
            prompt: PromptConfig::default(),
        }
    }
}

impl BeamClient {
    fn new(config: ClientConfig) -> Self {
        Self {
            sessions: Arc::new(Mutex::new(HashMap::new())),
            binary_cache: Arc::new(Mutex::new(HashMap::new())),
            config,
        }
    }

    async fn start_listener(
        &self,
        session_id: String,
        addr: SocketAddr,
        ssh_host: Option<String>,
        control_path: Option<String>,
    ) -> Result<u16> {
        let listener = TcpListener::bind(addr).await?;
        let actual_port = listener.local_addr()?.port();

        // Set up reverse port forward if SSH host provided
        if let (Some(host), Some(ctrl_path)) = (ssh_host, control_path) {
            self.setup_reverse_forward(&host, actual_port, &ctrl_path)
                .await?;
        }

        let binary_cache = self.binary_cache.clone();
        let config = self.config.clone();
        let session_id_for_spawn = session_id.clone();

        // Spawn listener in a detached thread with its own runtime
        // This ensures the listener survives even when the current tokio runtime is dropped
        // (e.g., when init command exits but the SSH session is still ongoing)
        std::thread::spawn(move || {
            let rt = tokio::runtime::Runtime::new().unwrap();
            rt.block_on(async move {
                Self::accept_loop(listener, binary_cache, config, session_id_for_spawn).await;
            });
        });

        let mut sessions_guard = self.sessions.lock().await;
        let key = session_id.clone();
        sessions_guard.insert(
            key,
            SessionInfo {
                session_id,
                port: actual_port,
            },
        );

        Ok(actual_port)
    }

    async fn setup_reverse_forward(
        &self,
        ssh_host: &str,
        port: u16,
        control_path: &str,
    ) -> Result<()> {
        let forward_spec = format!("{}:localhost:{}", port, port);
        let output = Command::new("ssh")
            .args([
                "-O",
                "forward",
                "-R",
                &forward_spec,
                "-S",
                control_path,
                ssh_host,
            ])
            .output()?;

        if !output.status.success() {
            eprintln!(
                "Warning: Failed to set up reverse forward: {}",
                String::from_utf8_lossy(&output.stderr)
            );
        }
        Ok(())
    }

    async fn accept_loop(
        listener: TcpListener,
        binary_cache: Arc<Mutex<HashMap<String, BinaryMetadata>>>,
        config: ClientConfig,
        session_id: String,
    ) {
        loop {
            match listener.accept().await {
                Ok((stream, addr)) => {
                    let binary_cache = binary_cache.clone();
                    let config = config.clone();
                    let session_id = session_id.clone();

                    tokio::spawn(async move {
                        match Self::handle_connection(stream, binary_cache, config, session_id)
                            .await
                        {
                            // Already reported in plain words.
                            Ok(())
                            | Err(ProtocolError::Blake3Mismatch { .. })
                            | Err(ProtocolError::VersionMismatch { .. }) => {}
                            Err(e) => eprintln!("beam: connection error from {}: {}", addr, e),
                        }
                    });
                }
                Err(e) => {
                    eprintln!("Accept error: {}", e);
                    break;
                }
            }
        }
    }

    async fn handle_connection(
        mut stream: TcpStream,
        binary_cache: Arc<Mutex<HashMap<String, BinaryMetadata>>>,
        config: ClientConfig,
        expected_session_id: String,
    ) -> Result<()> {
        let version = read_handshake(&mut stream).await?;

        // Read messages line by line (JSON Lines)
        let (rd, mut wr) = stream.into_split();
        let mut reader = BufReader::new(rd);
        let mut line = String::new();

        if version != PROTOCOL_VERSION {
            return Self::refuse_version(&mut reader, &mut wr, &version).await;
        }

        while reader.read_line(&mut line).await? > 0 {
            let trimmed = line.trim();
            if trimmed.is_empty() {
                line.clear();
                continue;
            }

            let msg: ClientMessage = serde_json::from_str(trimmed)?;

            if msg.session_id() != expected_session_id {
                let err = ServerMessage::Error {
                    session_id: expected_session_id.clone(),
                    message: format!(
                        "Session ID mismatch: expected {}, got {}",
                        expected_session_id,
                        msg.session_id()
                    ),
                };
                Self::send_message(&mut wr, &err).await?;
                return Err(ProtocolError::SessionMismatch {
                    expected: expected_session_id,
                    actual: msg.session_id().to_string(),
                });
            }

            match msg {
                ClientMessage::Request {
                    session_id,
                    command,
                    args,
                    arch,
                    os,
                } => {
                    let req = BinaryRequest {
                        session_id,
                        command,
                        args,
                        arch,
                        os,
                    };
                    Self::handle_request(&mut wr, &binary_cache, &config, req).await?;
                }
                ClientMessage::Ping { session_id } => {
                    let pong = ServerMessage::Pong { session_id };
                    Self::send_message(&mut wr, &pong).await?;
                }
            }

            line.clear();
        }

        Ok(())
    }

    /// The handler speaks another protocol version. Say so here, and tell the
    /// handler in an `error` message: its first JSON line carries the session
    /// id it expects, and every Beam version so far prints a client `error`.
    async fn refuse_version(
        reader: &mut BufReader<tokio::net::tcp::OwnedReadHalf>,
        wr: &mut tokio::net::tcp::OwnedWriteHalf,
        theirs: &str,
    ) -> Result<()> {
        let message = version_mismatch_message(PROTOCOL_VERSION, theirs);
        eprintln!("\r\nbeam: refused a request from the server's beam-server-handler: {message}\r");
        let mut line = String::new();
        let wait = std::time::Duration::from_secs(5);
        if let Ok(Ok(n)) = tokio::time::timeout(wait, reader.read_line(&mut line)).await
            && n > 0
            && let Ok(v) = serde_json::from_str::<serde_json::Value>(line.trim())
            && let Some(session_id) = v.get("session_id").and_then(|s| s.as_str())
        {
            let err = ServerMessage::Error {
                session_id: session_id.to_string(),
                message: message.clone(),
            };
            let _ = Self::send_message(wr, &err).await;
        }
        Err(ProtocolError::VersionMismatch {
            ours: PROTOCOL_VERSION.to_string(),
            theirs: theirs.to_string(),
        })
    }

    async fn handle_request(
        wr: &mut (impl AsyncWriteExt + Unpin),
        binary_cache: &Arc<Mutex<HashMap<String, BinaryMetadata>>>,
        config: &ClientConfig,
        req: BinaryRequest,
    ) -> Result<()> {
        let BinaryRequest {
            session_id,
            command,
            args,
            arch,
            os,
        } = req;

        // Find binary
        let binary_path = Self::find_binary(&command, config)?;

        let (exists, compatible, metadata) = if let Some(path) = binary_path {
            let meta = Self::get_binary_metadata(&path, binary_cache, &arch, &os).await?;
            let compatible = meta.arch == arch && meta.os == os;
            (true, compatible, Some(meta))
        } else {
            (false, false, None)
        };

        let response = ServerMessage::Response {
            session_id: session_id.clone(),
            exists,
            compatible: exists && compatible,
            size: metadata.as_ref().map(|m| m.size),
            blake3_hash: metadata.as_ref().map(|m| m.blake3_hash.clone()),
            error: if !exists {
                Some(format!("Command '{}' not found on client", command))
            } else {
                None
            },
        };

        Self::send_message(wr, &response).await?;

        let Some(meta) = metadata.filter(|_| exists && compatible) else {
            return Ok(());
        };

        // Ask the user on the client's terminal. This blocks, so keep it off
        // the async workers.
        let text = Self::prompt_text(&command, &args, &meta, &config.prompt);
        let prompt_cfg = config.prompt.clone();
        let decision = tokio::task::spawn_blocking(move || prompt::ask(&prompt_cfg, &text))
            .await
            .unwrap_or_else(|e| Decision::NoTty(format!("prompt task failed: {e}")));

        let approval = ServerMessage::Approval {
            session_id: session_id.clone(),
            approved: decision.approved(),
            reason: decision.reason(),
        };
        Self::send_message(wr, &approval).await?;

        if decision.approved() {
            Self::stream_binary(wr, &meta).await?;
        }

        Ok(())
    }

    fn prompt_text(
        command: &str,
        args: &[String],
        meta: &BinaryMetadata,
        prompt: &PromptConfig,
    ) -> String {
        let shown_args = if args.is_empty() {
            String::new()
        } else {
            format!(" {}", args.join(" "))
        };
        format!(
            "\nbeam: the remote host asked to run `{command}{shown_args}`, which it does not have.\n\
             beam:   send {} ({} bytes, blake3 {}…) and run it there?\n\
             beam: allow? [y/N] (denies in {}s) ",
            meta.path.display(),
            meta.size,
            &meta.blake3_hash[..16],
            prompt.timeout.as_secs()
        )
    }

    /// Stream the file the user approved as raw frames. The server checks the
    /// stream against the size and hash it was shown, so if the file changed
    /// since then the server refuses to run it; we warn about it here as well.
    async fn stream_binary(
        wr: &mut (impl AsyncWriteExt + Unpin),
        meta: &BinaryMetadata,
    ) -> Result<()> {
        let mut file = tokio::fs::File::open(&meta.path).await?;
        let (sent_hash, _sent) = frame::send_binary(&mut file, wr).await?;

        if sent_hash != meta.blake3_hash {
            eprintln!(
                "beam: warning: {} changed after it was approved; the server will refuse it",
                meta.path.display()
            );
            return Err(ProtocolError::Blake3Mismatch {
                expected: meta.blake3_hash.clone(),
                actual: sent_hash,
            });
        }

        Ok(())
    }

    async fn send_message(
        wr: &mut (impl AsyncWriteExt + Unpin),
        msg: &ServerMessage,
    ) -> Result<()> {
        let json = serde_json::to_string(msg)?;
        wr.write_all(json.as_bytes()).await?;
        wr.write_all(b"\n").await?;
        wr.flush().await?;
        Ok(())
    }

    fn find_binary(command: &str, config: &ClientConfig) -> Result<Option<PathBuf>> {
        // Check PATH first
        if let Ok(path) = which::which(command) {
            return Ok(Some(path));
        }

        // Check allowed paths
        for base in &config.allowed_paths {
            let path = base.join(command);
            if path.exists() && path.is_file() {
                #[cfg(unix)]
                {
                    use std::os::unix::fs::PermissionsExt;
                    if let Ok(metadata) = path.metadata()
                        && metadata.permissions().mode() & 0o111 != 0
                    {
                        return Ok(Some(path));
                    }
                }
                #[cfg(not(unix))]
                {
                    return Ok(Some(path));
                }
            }
        }

        Ok(None)
    }

    async fn get_binary_metadata(
        path: &Path,
        cache: &Arc<Mutex<HashMap<String, BinaryMetadata>>>,
        _expected_arch: &str,
        _expected_os: &str,
    ) -> Result<BinaryMetadata> {
        // Key on size and mtime too, so a binary that is rebuilt or replaced
        // during a long session is re-hashed instead of served with a stale hash.
        let fs_meta = tokio::fs::metadata(path).await?;
        let mtime = fs_meta
            .modified()
            .ok()
            .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
            .map(|d| d.as_nanos())
            .unwrap_or(0);
        let key = format!("{}\0{}\0{}", path.to_string_lossy(), fs_meta.len(), mtime);

        // Check cache first
        {
            let cache_guard = cache.lock().await;
            if let Some(meta) = cache_guard.get(&key) {
                return Ok(meta.clone());
            }
        }

        // Compute metadata
        let size = fs_meta.len();
        let blake3_hash = compute_blake3_file(path)?;

        // Detect architecture (simplified)
        let arch = std::env::consts::ARCH.to_string();
        let os = std::env::consts::OS.to_string();

        let meta = BinaryMetadata {
            path: path.to_path_buf(),
            size,
            blake3_hash,
            arch,
            os,
        };

        cache.lock().await.insert(key, meta.clone());
        Ok(meta)
    }
}

#[tokio::main]
async fn main() -> Result<()> {
    let cli = Cli::parse();
    let config = ClientConfig::default();
    let client = BeamClient::new(config);

    match cli.command {
        Commands::Listen {
            session_id,
            port,
            host,
            ssh_host,
            control_path,
        } => {
            let addr = format!("{}:{}", host, port)
                .to_socket_addrs()?
                .next()
                .ok_or(ProtocolError::InvalidFormat)?;
            let actual_port = client
                .start_listener(session_id, addr, ssh_host, control_path)
                .await?;
            println!("Listening on port {}", actual_port);
            // Keep running
            tokio::signal::ctrl_c().await?;
        }
        Commands::Ssh { args } => {
            if ssh::is_passthrough(&args) {
                std::process::exit(ssh::exec_plain(&args));
            }
            let listener = match TcpListener::bind("127.0.0.1:0").await {
                Ok(l) => l,
                Err(e) => {
                    eprintln!("beam: cannot start listener ({e}); running plain ssh");
                    std::process::exit(ssh::exec_plain(&args));
                }
            };
            let port = listener.local_addr()?.port();
            let session_id = Uuid::new_v4().to_string();
            let config = ClientConfig::default();
            let prompt = config.prompt.clone();
            let binary_cache = Arc::new(Mutex::new(HashMap::new()));
            tokio::spawn(BeamClient::accept_loop(
                listener,
                binary_cache,
                config,
                session_id.clone(),
            ));
            let code = tokio::task::spawn_blocking(move || {
                ssh::run_session(&session_id, port, &args, &prompt)
            })
            .await
            .unwrap_or(255);
            std::process::exit(code);
        }
        Commands::ShellInit { shell } => match ssh::shell_init(&shell) {
            Some(script) => print!("{script}"),
            None => {
                eprintln!("beam: unsupported shell '{shell}' (use bash, zsh or fish)");
                std::process::exit(2);
            }
        },
        Commands::FindBinary { command } => {
            if let Some(path) = BeamClient::find_binary(&command, &ClientConfig::default())? {
                println!("{}", path.display());
            } else {
                eprintln!("Binary not found: {}", command);
                std::process::exit(1);
            }
        }
        Commands::Hash { path } => {
            let hash = compute_blake3_file(&path)?;
            println!("{}  {}", hash, path.display());
        }
    }

    Ok(())
}
